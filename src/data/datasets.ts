/** סדר הגרסאות לתצוגה: העדכנית קודם. */
export const VERSION_IDS: VersionId[] = ['v2', 'v1'];

export const DEFAULT_VERSION: VersionId = 'v2';

/**
 * ההחזקות של בעלים בגרסה נתונה.
 * אם ה-hash לא נמצא בגרסה (למשל השם נכתב אחרת בין הגרסאות), מקשרים דרך הגרסאות האחרות:
 * מוצאים שם את ה-hash של מס׳ הזהות של אותו בעלים, ומחפשים אותו בגרסה המבוקשת.
 */
export function resolveHoldings(version: VersionId, hash: string): OwnerHolding[] {
  const direct = DATASETS[version].getHoldingsByHash(hash);
  if (direct.length > 0 || !hash) return direct;

  const linkedIds = new Set<string>();
  for (const other of VERSION_IDS) {
    if (other === version) continue;
    for (const h of DATASETS[other].getHoldingsByHash(hash)) {
      // רק ת.ז. של אותו צד (בעלים/חוכר) שה-hash תאם לו
      if (h.nameHash === hash || h.idHash === hash) {
        if (h.idHash) linkedIds.add(h.idHash);
      } else if (h.altIdHash) {
        linkedIds.add(h.altIdHash);
      }
    }
  }
  if (linkedIds.size === 0) return [];
  return DATASETS[version].owners.filter(
    (o) => linkedIds.has(o.idHash) || linkedIds.has(o.altIdHash),
  );
}
